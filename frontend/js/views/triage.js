Views.triage = async (el) => {
  document.title = I18n.t('x_title') + ' · ' + I18n.t('app_name');
  const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

  if (!Auth.can('asha_worker', 'doctor')) {
    el.innerHTML = `<div class="card p-6 text-center"><p class="text-slate-600 dark:text-slate-300 mb-4">🚫 ${esc(I18n.t('access_denied'))}</p><button class="btn btn-primary btn-sm" data-back>${esc(I18n.t('dashboard'))}</button></div>`;
    el.querySelector('[data-back]').onclick = () => Router.go('#/dashboard');
    return;
  }

  const SYMPTOMS = ['fever', 'cough', 'chest_pain', 'breathless', 'bleeding', 'vomiting', 'diarrhoea', 'headache', 'injury', 'labour_pains', 'unconscious', 'seizure'];
  const RED_SYMPTOMS = ['chest_pain', 'breathless', 'bleeding', 'unconscious', 'seizure', 'labour_pains'];
  const YELLOW_SYMPTOMS = ['fever', 'vomiting', 'diarrhoea', 'injury'];

  const num = v => { const n = parseFloat(v); return isNaN(n) ? null : n; };

  const assess = (vals) => {
    const reasons = [];
    const red = [], yellow = [];
    const spo2 = num(vals.spo2), sys = num(vals.sysBp), dia = num(vals.diaBp),
          pulse = num(vals.pulse), temp = num(vals.temp);
    const syms = SYMPTOMS.filter(s => vals['sym_' + s]);

    if (spo2 !== null) {
      if (spo2 < 90) red.push('reason_spo2_red');
      else if (spo2 <= 94) yellow.push('reason_spo2_yellow');
    }
    if (sys !== null) {
      if (sys >= 180 || sys < 90) red.push('reason_sys_red');
      else if (sys >= 160 || sys <= 100) yellow.push('reason_sys_yellow');
    }
    if (pulse !== null) {
      if (pulse > 120 || pulse < 50) red.push('reason_pulse_red');
      else if (pulse > 100 || pulse < 60) yellow.push('reason_pulse_yellow');
    }
    if (temp !== null) {
      if (temp >= 40) red.push('reason_temp_red');
      else if (temp >= 38.5) yellow.push('reason_temp_yellow');
    }
    syms.forEach(s => {
      if (RED_SYMPTOMS.includes(s)) red.push({ k: 'reason_sym_red', sym: I18n.t('sym_' + s) });
      else if (YELLOW_SYMPTOMS.includes(s)) yellow.push({ k: 'reason_sym_yellow', sym: I18n.t('sym_' + s) });
    });

    red.forEach(r => reasons.push({ level: 'red', text: typeof r === 'string' ? I18n.t(r) : I18n.t(r.k).replace('{sym}', r.sym) }));
    yellow.forEach(y => reasons.push({ level: 'yellow', text: typeof y === 'string' ? I18n.t(y) : I18n.t(y.k).replace('{sym}', y.sym) }));

    let level = 'green';
    if (red.length) level = 'red';
    else if (yellow.length) level = 'yellow';

    return { level, reasons, data: { ...vals, symptoms: syms, spo2, sysBp: sys, diaBp: dia, pulse, temp, level } };
  };

  const levelStyle = (level) => ({
    red: { card: 'border-red-500 bg-red-50 dark:bg-red-950/40', dot: 'bg-red-500', label: I18n.t('level_red'), text: 'text-red-800 dark:text-red-200' },
    yellow: { card: 'border-amber-500 bg-amber-50 dark:bg-amber-950/40', dot: 'bg-amber-500', label: I18n.t('level_yellow'), text: 'text-amber-800 dark:text-amber-200' },
    green: { card: 'border-green-500 bg-green-50 dark:bg-green-950/40', dot: 'bg-green-500', label: I18n.t('level_green'), text: 'text-green-800 dark:text-green-200' }
  }[level]);

  let result = null;

  const render = () => {
    const symptomBoxes = SYMPTOMS.map(s => `
      <label class="flex items-center gap-2 text-sm text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 rounded-lg px-3 py-2 cursor-pointer hover:bg-slate-50 dark:hover:bg-slate-800">
        <input type="checkbox" name="sym_${s}" class="w-4 h-4 accent-teal-600" />
        ${esc(I18n.t('sym_' + s))}
      </label>`).join('');

    el.innerHTML = `
      <div class="space-y-4 max-w-3xl mx-auto">
        <div>
          <h1 class="text-xl sm:text-2xl font-bold text-slate-900 dark:text-white">🩺 ${esc(I18n.t('x_title'))}</h1>
          <p class="text-sm text-slate-500 dark:text-slate-400">${esc(I18n.t('triage_sub'))}</p>
        </div>

        <form id="triage-form" class="card p-4 sm:p-6 space-y-4">
          <div class="grid grid-cols-1 sm:grid-cols-2 gap-4">
            ${Forms.field({ label: I18n.t('field_patient_name'), name: 'patientName', type: 'text', required: true })}
            ${Forms.field({ label: I18n.t('field_age'), name: 'age', type: 'number', min: 0, max: 120 })}
            ${Forms.field({ label: I18n.t('field_gender'), name: 'gender', type: 'select', options: [
              { value: '', label: '—' },
              { value: 'female', label: I18n.t('female') },
              { value: 'male', label: I18n.t('male') },
              { value: 'other', label: I18n.t('other') }
            ]})}
            <div class="flex items-end pb-1">
              <label class="flex items-center gap-2 text-sm font-medium text-slate-700 dark:text-slate-300 cursor-pointer">
                <input type="checkbox" name="pregnant" class="w-5 h-5 accent-teal-600" />
                ${esc(I18n.t('field_pregnant'))}
              </label>
            </div>
          </div>

          <div>
            <p class="text-sm font-medium text-slate-700 dark:text-slate-300 mb-2">Vitals</p>
            <div class="grid grid-cols-2 sm:grid-cols-3 gap-4">
              ${Forms.field({ label: I18n.t('field_temp'), name: 'temp', type: 'number', min: 30, max: 45, step: '0.1' })}
              ${Forms.field({ label: I18n.t('field_sys_bp'), name: 'sysBp', type: 'number', min: 40, max: 300 })}
              ${Forms.field({ label: I18n.t('field_dia_bp'), name: 'diaBp', type: 'number', min: 20, max: 200 })}
              ${Forms.field({ label: I18n.t('field_pulse'), name: 'pulse', type: 'number', min: 20, max: 250 })}
              ${Forms.field({ label: I18n.t('field_spo2'), name: 'spo2', type: 'number', min: 50, max: 100 })}
              ${Forms.field({ label: I18n.t('field_resp_rate'), name: 'respRate', type: 'number', min: 5, max: 80 })}
              ${Forms.field({ label: I18n.t('field_weight'), name: 'weight', type: 'number', min: 1, max: 300, step: '0.1' })}
            </div>
          </div>

          <div>
            <p class="text-sm font-medium text-slate-700 dark:text-slate-300 mb-2">${esc(I18n.t('field_symptoms'))}</p>
            <div class="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-2">${symptomBoxes}</div>
          </div>

          ${Forms.field({ label: I18n.t('field_notes'), name: 'notes', type: 'textarea', rows: 3 })}

          <div class="flex flex-col sm:flex-row gap-2">
            <button type="submit" class="btn btn-primary flex-1">${esc(I18n.t('assess_btn'))}</button>
            <button type="button" class="btn btn-outline" data-reset>${esc(I18n.t('reset_btn'))}</button>
          </div>
        </form>

        <div id="triage-result"></div>
      </div>`;

    el.querySelector('[data-reset]').addEventListener('click', () => { result = null; render(); });

    el.querySelector('#triage-form').addEventListener('submit', (e) => {
      e.preventDefault();
      const form = e.target;
      if (!Forms.validate(form)) return;
      const vals = Forms.values(form);
      if (vals.pregnant && (vals.gender === 'male')) {
        Toast.warning(I18n.t('r_pregnant_flag'));
      }
      result = assess(vals);
      renderResult();
    });

    if (result) renderResult();
  };

  const renderResult = () => {
    const box = el.querySelector('#triage-result');
    if (!box || !result) return;
    const st = levelStyle(result.level);
    const adviceKey = result.level === 'red' ? 'advice_red' : result.level === 'yellow' ? 'advice_yellow' : 'advice_green';

    const reasonsHTML = result.reasons.length
      ? `<ul class="mt-2 space-y-1">${result.reasons.map(r => `
        <li class="flex items-start gap-2 text-sm">
          <span class="mt-1.5 w-2 h-2 rounded-full flex-shrink-0 ${r.level === 'red' ? 'bg-red-500' : 'bg-amber-500'}"></span>
          <span class="text-slate-700 dark:text-slate-300">${esc(r.text)}</span>
        </li>`).join('')}</ul>`
      : '';

    box.innerHTML = `
      <div class="border-2 ${st.card} rounded-xl p-5 space-y-4">
        <div class="flex items-center gap-3">
          <span class="w-4 h-4 rounded-full ${st.dot} animate-pulse"></span>
          <h2 class="text-lg font-bold ${st.text}">${esc(I18n.t('result_title'))}: ${esc(st.label)}</h2>
        </div>

        ${result.reasons.length ? `<div><p class="text-sm font-semibold ${st.text}">${esc(I18n.t('reasons_title'))}</p>${reasonsHTML}</div>` : ''}

        <div class="bg-white/70 dark:bg-slate-900/40 rounded-lg p-3">
          <p class="text-sm font-semibold ${st.text}">${esc(I18n.t('advice_title'))}</p>
          <p class="text-sm text-slate-700 dark:text-slate-300 mt-1">${esc(I18n.t(adviceKey))}</p>
        </div>

        <div class="grid grid-cols-1 sm:grid-cols-3 gap-2">
          <button class="btn ${result.level === 'red' ? 'btn-danger' : 'btn-primary'}" data-t-save>💾 ${esc(I18n.t('save_triage'))}</button>
          <button class="btn btn-outline" data-t-referral>↗️ ${esc(I18n.t('create_referral'))}</button>
          <button class="btn btn-outline" data-t-book>📅 ${esc(I18n.t('book_appointment'))}</button>
        </div>
      </div>`;

    box.querySelector('[data-t-save]').addEventListener('click', async () => {
      if (!result) { Toast.info(I18n.t('assess_first')); return; }
      try {
        const res = await Api.post('/triage', result.data);
        if (res && res.queued) Toast.info(I18n.t('offline_queued')); else Toast.success(I18n.t('triage_saved'));
      } catch (e) { Toast.error(I18n.t('operation_failed')); }
    });

    box.querySelector('[data-t-referral]').addEventListener('click', async () => {
      if (!result) { Toast.info(I18n.t('assess_first')); return; }
      try {
        const res = await Api.post('/referrals', {
          patientName: result.data.patientName,
          reason: 'Triage ' + result.level.toUpperCase(),
          priority: result.level
        });
        if (res && res.queued) Toast.info(I18n.t('offline_queued')); else Toast.success(I18n.t('referral_created'));
        Router.go('#/referrals');
      } catch (e) { Toast.error(I18n.t('operation_failed')); }
    });

    box.querySelector('[data-t-book]').addEventListener('click', () => {
      Router.go('#/appointments');
    });

    box.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  };

  render();
};
